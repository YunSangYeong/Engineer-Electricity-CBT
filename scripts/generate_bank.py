def add(subject, family, index, topic, text, result, unit, explanation, values):
    # Decimal half-up also handles the exact 0.875 → 0.88 boundary.
    rounded = float(Decimal(str(result)).quantize(Decimal('0.01'), rounding=ROUND_HALF_UP))
    numeric = [rounded, round(rounded * 0.5, 2), round(rounded * 1.5, 2), round(rounded * 2, 2)]
    shift = index % 4
    numeric = numeric[shift:] + numeric[:shift]
    assert len(set(numeric)) == 4 and rounded > 0
    q = common(subject, f'EE-{family}-{index + 1:02}', topic)
    q.update(question=text + ' (소수 셋째 자리에서 반올림하여 둘째 자리까지 구한다.)',
             choices=[f'{v:g} {unit}' for v in numeric], answer=numeric.index(rounded) + 1,
             explanation=explanation + f' 따라서 답은 {rounded:g} {unit}이다. 보기의 값은 같은 단위이며 반올림 후 하나만 일치한다.',
             family=family, calculation={'kind': family, 'values': values, 'result': rounded, 'unit': unit, 'precision': 2})
    questions.append(q)

